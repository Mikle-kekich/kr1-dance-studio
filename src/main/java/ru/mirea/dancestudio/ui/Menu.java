package ru.mirea.dancestudio.ui;

/**
 * Пункт консольного интерфейса, который умеет показать своё меню и обработать выбор.
 * Главное меню хранит подменю как объекты этого интерфейса и вызывает run() полиморфно.
 */
public interface Menu {

    /** Заголовок меню. */
    String title();

    /** Показывает меню в цикле, пока пользователь не выберет «Назад» (или «Выход»). */
    void run();
}
